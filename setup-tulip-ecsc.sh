doctor_main() {
    local tulip_dir role=auto failures=0
    tulip_dir="$(default_tulip_dir)"
    while (($#)); do
        case "$1" in
            --tulip-dir) tulip_dir="${2:?missing value}"; shift 2 ;;
            --role) role="${2:?missing value}"; shift 2 ;;
            -h|--help) usage; exit 0 ;;
            *) die "unknown doctor option: $1" ;;
        esac
    done
    [[ "$role" == auto || "$role" == offsite || "$role" == vulnbox ]] \
        || die "--role must be auto, offsite, or vulnbox"
    if [[ "$role" == auto ]]; then
        if [[ -f /etc/ecsc-tulip/forwarder ]]; then role=vulnbox; else role=offsite; fi
    fi

    check_ok() { log "doctor: $1"; }
    check_fail() { printf 'error: doctor: %s\n' "$1" >&2; failures=$((failures + 1)); }

    if [[ "$(uname -s)" == Linux ]]; then
        check_ok "Linux host"
    else
        check_fail "deployment host must be Linux"
    fi
    if [[ "$role" == offsite ]]; then
        if [[ -d "$tulip_dir" && -f "$tulip_dir/docker-compose.yml" ]]; then
            check_ok "Rose checkout found at $tulip_dir"
        else
            check_fail "Rose checkout missing at $tulip_dir"
        fi
        if command -v docker >/dev/null 2>&1; then
            check_ok "Docker CLI: $(docker --version 2>/dev/null || printf unknown)"
            if docker compose version >/dev/null 2>&1; then
                check_ok "Docker Compose v2: $(docker compose version --short 2>/dev/null || printf installed)"
            else
                check_fail "Docker Compose v2 plugin is missing"
            fi
            if docker info >/dev/null 2>&1; then
                check_ok "Docker daemon reachable"
            else
                check_fail "Docker daemon is not reachable"
            fi
        else
            check_fail "Docker Engine is missing"
        fi
        for command in python3 rsync ssh ssh-keygen ssh-keyscan; do
            if command -v "$command" >/dev/null 2>&1; then
                check_ok "$command available"
            else
                check_fail "$command missing"
            fi
        done
        if [[ -f "$tulip_dir/services/timescale/Dockerfile" ]] \
            && grep -Eq 'clang19.*llvm19|llvm19.*clang19' "$tulip_dir/services/timescale/Dockerfile"; then
            check_ok "Timescale image uses clang19/llvm19"
        else
            check_fail "Timescale image is not pinned to clang19/llvm19"
        fi
        if [[ -f "$tulip_dir/.env.ecsc" && -f "$tulip_dir/docker-compose.ecsc.yml" ]] \
            && command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
            if (
                cd -- "$tulip_dir"
                docker compose --env-file .env.ecsc \
                    -f docker-compose.yml -f docker-compose.ecsc.yml config >/dev/null
            ); then
                check_ok "generated Compose configuration is valid"
            else
                check_fail "generated Compose configuration is invalid"
            fi
            if grep -q '^PCAP_OVER_IP=$' "$tulip_dir/.env.ecsc"; then
                if [[ -x /usr/local/sbin/rose-pcap-receive ]]; then
                    check_ok "durable offsite receiver installed"
                else
                    check_fail "durable mode configured but receiver is missing"
                fi
            else
                check_fail "legacy stream ingest is configured; durable push is not active"
            fi
            if docker info >/dev/null 2>&1; then
                local running_services service
                running_services="$(
                    cd -- "$tulip_dir"
                    docker compose --env-file .env.ecsc \
                        -f docker-compose.yml -f docker-compose.ecsc.yml \
                        ps --status running --services 2>/dev/null || true
                )"
                for service in timescale api frontend assembler service-sync; do
                    if grep -qx "$service" <<<"$running_services"; then
                        check_ok "$service container running"
                    else
                        check_fail "$service container is not running"
                    fi
                done
            fi
        else
            check_fail "run offsite setup to create .env.ecsc and docker-compose.ecsc.yml"
        fi
    else
        for command in tcpdump python3 rsync ssh ssh-keygen ssh-keyscan flock systemctl; do
            if command -v "$command" >/dev/null 2>&1; then
                check_ok "$command available"
            else
                check_fail "$command missing"
            fi
        done
        if [[ -s /etc/ecsc-tulip/forwarder ]]; then
            check_ok "forwarder configuration installed"
        else
            check_fail "forwarder configuration missing"
        fi
        if [[ -s /root/.ssh/rose-pcap-push && -s /root/.ssh/rose-offsite-known-hosts ]]; then
            check_ok "forwarding identity and pinned host key installed"
        else
            check_fail "forwarding key or offsite known-host key missing"
        fi
        for unit in rose-pcap-capture.service rose-pcap-stage.timer rose-pcap-push.timer rose-pcap-health.timer; do
            if systemctl is-enabled --quiet "$unit" && systemctl is-active --quiet "$unit"; then
