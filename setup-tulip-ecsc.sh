            fi
        done
        if [[ -d "$PCAP_SPOOL_DIR/ready" ]]; then
            local queued last now available_kb
            queued="$(find "$PCAP_SPOOL_DIR/ready" -maxdepth 1 -type f -name '*.pcap' | wc -l | tr -d ' ')"
            check_ok "durable retry queue contains $queued file(s)"
            now="$(date +%s)"; last=0
            [[ -s "$FORWARDER_STATE_DIR/last-success-epoch" ]] \
                && read -r last <"$FORWARDER_STATE_DIR/last-success-epoch"
            if ((queued > 0 && now - last > 120)); then
                check_fail "retry queue has not delivered successfully in the last two minutes"
            elif ((last > 0)); then
                check_ok "forwarder has a recorded successful delivery"
            fi
            available_kb="$(df -Pk "$PCAP_SPOOL_DIR" | awk 'NR==2 {print $4}')"
            if ((available_kb >= 1048576)); then
                check_ok "PCAP spool has at least 1 GiB free"
            else
                check_fail "PCAP spool has less than 1 GiB free"
            fi
        else
            check_fail "durable retry queue is missing"
        fi
    fi

    ((failures == 0)) || die "doctor found $failures problem(s)"
    log "doctor: Rose deployment is compatible and healthy"
}

main() {
    (($#)) || { usage; exit 1; }
    local mode="$1"; shift
    case "$mode" in
        offsite) offsite_main "$@" ;;
        vulnbox) vulnbox_main "$@" ;;
        doctor) doctor_main "$@" ;;
        -h|--help|help) usage ;;
        *) usage >&2; die "first argument must be offsite, vulnbox, or doctor" ;;
    esac
}

main "$@"
