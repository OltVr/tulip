set -Eeuo pipefail

readonly FAUST_TICK_START_DEFAULT="2026-09-27T13:00:00Z"
readonly FAUST_TICK_LENGTH_MS="45000"
readonly FAUST_FLAG_LIFETIME_TICKS="5"
readonly PCAP_BROKER_REV="fe3c0b2cdfa2fcf3272ecfcf5392b241082beaa1"
readonly CADDY_IMAGE="caddy:2.11.4-alpine"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
readonly SCRIPT_DIR
readonly PCAP_SPOOL_DIR="/var/spool/rose-pcap"
readonly FORWARDER_STATE_DIR="/var/lib/rose-forwarder"

log() { printf '[+] %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
need_command() { command -v "$1" >/dev/null 2>&1 || die "required command not found: $1"; }

usage() {
    cat <<'EOF'
Configure Tulip for FAUST CTF over the game VPN using live PCAP-over-IP.

Usage:
  setup-tulip-ecsc.sh offsite --team-id ID [options]
  setup-tulip-ecsc.sh vulnbox --public-key-file FILE [options]
  setup-tulip-ecsc.sh doctor [--tulip-dir DIR]

Offsite server:
  --team-id ID             FAUST team number; vulnbox defaults to fd66:666:<ID>::2
  --vulnbox-ip ADDR        Override the vulnbox IPv4/IPv6 address
  --tulip-dir DIR          Default: ./tulip beside this script
  --ui-vpn-ip ADDR         Bind Tulip directly to this address instead of public HTTPS
  --ui-port PORT           Direct UI port with --ui-vpn-ip; default: 3000
  --public-ip ADDR         Public UI IP when no domain is used
  --public-port PORT       Public HTTPS port; default: 443, useful fallback: 8443
  --domain NAME            Public DNS name; provides browser-trusted HTTPS
  --auth-user USER         Public HTTPS username; default: team
  --auth-password PASS     Public HTTPS password; generated when omitted
  --tick-start TIMESTAMP   Default: FAUST 2026 scoring start
  --service PORT:NAME      Initial mapping; repeat as needed
  --push-public-key-file FILE  Vulnbox forwarding key; enables durable push ingest
  --push-public-key KEY    Vulnbox forwarding key as a literal SSH public key
  --start                  Verify SSH, build, and start the stack
  --force                  Replace changed generated files

Vulnbox:
  --public-key-file FILE    Public capture key generated by offsite mode
  --public-key KEY          Public capture key as a literal ssh-ed25519/... string
  --team-id ID              FAUST team number; vulnbox IP becomes fd66:666:<ID>::2
  --vulnbox-ip ADDR         Override the vulnbox IPv4/IPv6 address in services.json
  --game-interface IFACE   Auto-detected when omitted
  --capture-filter FILTER  Default excludes SSH, retired stream 4242, and 4444
  --offsite-host HOST      Enable durable PCAP forwarding to this Rose server
  --offsite-port PORT      SSH port on the offsite host; default: 22
  --offsite-user USER      Restricted receiver account; default: root
  --offsite-dir DIR        Receiver traffic directory; default: /root/tulip/.ecsc/traffic
  --start                  Start capture, staging, forwarding, and health timers
  --force                  Replace changed generated files

Recommended durable order:
  1. Run offsite once without --start; copy .ecsc/ssh/id_ed25519.pub to the vulnbox.
  2. Run vulnbox with --public-key-file; it creates /root/.ssh/rose-pcap-push.pub.
  3. Copy that push public key to the offsite host.
  4. Run offsite with --push-public-key-file and --start.
  5. Run vulnbox with --offsite-host and --start.

The vulnbox rotates PCAPs into a durable queue. Failed transfers stay queued and
are retried every five seconds. The legacy offsite-pull stream remains available
only when no forwarding key has been configured.
EOF
}

write_generated() {
    local target="$1" force="$2" mode="${3:-0600}" tmp
    tmp="$(mktemp)"
    cat >"$tmp"
    if [[ -e "$target" ]]; then
        if cmp -s "$tmp" "$target"; then
            rm -f -- "$tmp"
            chmod "$mode" "$target"
            return
        fi
        if [[ "$force" != 1 ]]; then
            rm -f -- "$tmp"
            die "$target differs; inspect it or rerun with --force"
        fi
    fi
    mkdir -p -- "$(dirname -- "$target")"
    chmod "$mode" "$tmp"
    mv -f -- "$tmp" "$target"
}

validate_ipv4() {
    local ip="$1" octet
    local -a octets
    [[ "$ip" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || return 1
    IFS=. read -r -a octets <<<"$ip"
    for octet in "${octets[@]}"; do
        ((10#$octet >= 0 && 10#$octet <= 255)) || return 1
    done
}

validate_ip() {
    local ip="$1"
    if validate_ipv4 "$ip"; then return 0; fi
    [[ "$ip" =~ ^[0-9A-Fa-f:.]+$ && "$ip" == *:* ]]
}

validate_port() {
    local port="$1"
    [[ "$port" =~ ^[0-9]+$ ]] || return 1
    ((port >= 1 && port <= 65535))
}

json_escape() {
    local value="$1"
    value=${value//\\/\\\\}; value=${value//\"/\\\"}
    value=${value//$'\n'/\\n}; value=${value//$'\r'/\\r}; value=${value//$'\t'/\\t}
    printf '%s' "$value"
}

url_host() {
    local host="$1"
    if [[ "$host" == *:* && "$host" != \[* ]]; then
        printf '[%s]' "$host"
    else
        printf '%s' "$host"
    fi
}

default_tulip_dir() {
    if [[ -f "$SCRIPT_DIR/docker-compose.yml" ]]; then
        printf '%s' "$SCRIPT_DIR"
    else
        printf '%s' "$SCRIPT_DIR/tulip"
    fi
}

build_services_json() {
    local vm_ip="$1"; shift
    local result='[' first=1 spec port name
    if (($# == 0)); then
        printf '[{"ip":"%s","port":-1,"name":"other"}]' "$(json_escape "$vm_ip")"
        return
    fi
    for spec in "$@"; do
        [[ "$spec" == *:* ]] || die "invalid --service '$spec'; expected PORT:NAME"
        port="${spec%%:*}"; name="${spec#*:}"
        validate_port "$port" || die "service port must be in 1-65535: $port"
        [[ -n "$name" ]] || die "service name cannot be empty"
        ((first)) || result+=','; first=0
        result+="{\"ip\":\"$(json_escape "$vm_ip")\",\"port\":$port,\"name\":\"$(json_escape "$name")\"}"
    done
    printf '%s]' "$result"
}

install_vulnbox_dependencies() {
    if command -v tcpdump >/dev/null 2>&1 && command -v python3 >/dev/null 2>&1 \
        && command -v ss >/dev/null 2>&1 && command -v sshd >/dev/null 2>&1 \
        && command -v rsync >/dev/null 2>&1 && command -v flock >/dev/null 2>&1; then
        return
    fi
    if command -v apt-get >/dev/null 2>&1; then
        apt-get update
        DEBIAN_FRONTEND=noninteractive apt-get install -y \
            tcpdump python3 iproute2 openssh-server openssh-client rsync util-linux findutils
    elif command -v dnf >/dev/null 2>&1; then
        dnf install -y tcpdump python3 iproute openssh-server openssh-clients rsync util-linux findutils
    elif command -v apk >/dev/null 2>&1; then
        apk add --no-cache tcpdump python3 iproute2 openssh-server openssh-client rsync util-linux findutils
    else
        die "install tcpdump, python3, iproute2, OpenSSH, rsync, and util-linux first"
    fi
}

install_offsite_dependencies() {
    local need_docker=0 need_compose=0
    command -v docker >/dev/null 2>&1 || need_docker=1
    if ((need_docker == 0)) && ! docker compose version >/dev/null 2>&1; then need_compose=1; fi

    if ((need_docker || need_compose)) || ! command -v rsync >/dev/null 2>&1 \
        || ! command -v ssh-keygen >/dev/null 2>&1 || ! command -v sshd >/dev/null 2>&1 \
        || ! command -v python3 >/dev/null 2>&1; then
        [[ ${EUID:-$(id -u)} -eq 0 ]] \
            || die "missing offsite dependencies; rerun as root so Docker Compose v2 and support tools can be installed"

        if command -v apt-get >/dev/null 2>&1; then
            apt-get update
            DEBIAN_FRONTEND=noninteractive apt-get install -y \
                ca-certificates curl openssl openssh-client openssh-server python3 rsync
            if ((need_docker)); then
                DEBIAN_FRONTEND=noninteractive apt-get install -y docker.io
            fi
            if ! docker compose version >/dev/null 2>&1; then
                DEBIAN_FRONTEND=noninteractive apt-get install -y docker-compose-v2 \
                    || DEBIAN_FRONTEND=noninteractive apt-get install -y docker-compose-plugin
            fi
        elif command -v dnf >/dev/null 2>&1; then
            dnf install -y ca-certificates curl openssl openssh-clients openssh-server python3 rsync
            if ((need_docker)); then
                dnf install -y dnf-plugins-core
                if [[ -r /etc/os-release ]]; then
                    # shellcheck source=/dev/null
                    source /etc/os-release
                fi
                local repo_family="${ID:-centos}"
                case "$repo_family" in fedora) ;; *) repo_family=centos ;; esac
                dnf config-manager --add-repo "https://download.docker.com/linux/$repo_family/docker-ce.repo"
                dnf install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
            elif ((need_compose)); then
                dnf install -y docker-compose-plugin
            fi
        elif command -v apk >/dev/null 2>&1; then
            apk add --no-cache ca-certificates curl openssl openssh-client openssh-server python3 rsync docker docker-cli-compose
        else
            die "unsupported package manager; install Docker Engine, Compose v2, OpenSSH, Python 3, and rsync"
        fi
    fi

    if command -v systemctl >/dev/null 2>&1; then
        systemctl enable --now docker
        systemctl enable --now ssh 2>/dev/null || systemctl enable --now sshd
    elif command -v rc-service >/dev/null 2>&1; then
        rc-update add docker default 2>/dev/null || true
        rc-service docker start
    fi
    need_command docker
    docker compose version >/dev/null 2>&1 || die "Docker Compose v2 installation failed"
}

ensure_timescale_clang19() {
    local tulip_dir="$1" dockerfile="$1/services/timescale/Dockerfile"
    [[ -f "$dockerfile" ]] || die "Timescale Dockerfile missing: $dockerfile"
    if grep -Eq 'clang15|llvm15' "$dockerfile"; then
        [[ -e "$dockerfile.before-clang19" ]] || cp -a -- "$dockerfile" "$dockerfile.before-clang19"
        python3 - "$dockerfile" <<'PYTHON'
from pathlib import Path
import sys

path = Path(sys.argv[1])
text = path.read_text(encoding="utf-8")
text = text.replace("clang15", "clang19").replace("llvm15", "llvm19")
path.write_text(text, encoding="utf-8")
PYTHON
        log "updated the Timescale build from clang/llvm 15 to 19 (backup: $dockerfile.before-clang19)"
    fi
    grep -Eq 'clang19.*llvm19|llvm19.*clang19' "$dockerfile" \
        || die "$dockerfile must install clang19 and llvm19"
}

offsite_main() {
    local team_id="" vulnbox_ip="" tulip_dir
    tulip_dir="$(default_tulip_dir)"
    local public_ip="" public_port=443 domain="" ui_vpn_ip="" ui_port=3000
    local auth_user="team" auth_password="" tick_start="$FAUST_TICK_START_DEFAULT"
    local push_public_key_file="" push_public_key_literal="" durable_push=0
    local start=0 force=0
    local -a service_specs=()

    while (($#)); do
        case "$1" in
            --team-id) team_id="${2:?missing value}"; shift 2 ;;
            --vulnbox-ip) vulnbox_ip="${2:?missing value}"; shift 2 ;;
            --tulip-dir) tulip_dir="${2:?missing value}"; shift 2 ;;
            --ui-vpn-ip) ui_vpn_ip="${2:?missing value}"; shift 2 ;;
            --ui-port) ui_port="${2:?missing value}"; shift 2 ;;
            --public-ip) public_ip="${2:?missing value}"; shift 2 ;;
            --public-port) public_port="${2:?missing value}"; shift 2 ;;
            --domain) domain="${2:?missing value}"; shift 2 ;;
            --auth-user) auth_user="${2:?missing value}"; shift 2 ;;
            --auth-password) auth_password="${2:?missing value}"; shift 2 ;;
            --tick-start) tick_start="${2:?missing value}"; shift 2 ;;
            --service) service_specs+=("${2:?missing value}"); shift 2 ;;
            --push-public-key-file) push_public_key_file="${2:?missing value}"; shift 2 ;;
            --push-public-key) push_public_key_literal="${2:?missing value}"; shift 2 ;;
            --start) start=1; shift ;;
            --force) force=1; shift ;;
            -h|--help) usage; exit 0 ;;
            *) die "unknown offsite option: $1" ;;
        esac
    done

    [[ "$team_id" =~ ^[0-9]+$ ]] || die "--team-id must be a number"
    ((team_id >= 1 && team_id <= 9999)) || die "--team-id must be between 1 and 9999"
    vulnbox_ip="${vulnbox_ip:-fd66:666:${team_id}::2}"
    validate_ip "$vulnbox_ip" || die "invalid vulnbox IP: $vulnbox_ip"
    validate_port "$public_port" || die "invalid --public-port"
    validate_port "$ui_port" || die "invalid --ui-port"
    if [[ -n "$public_ip" ]]; then validate_ip "$public_ip" || die "invalid public IP: $public_ip"; fi
    if [[ -n "$ui_vpn_ip" ]]; then validate_ip "$ui_vpn_ip" || die "invalid --ui-vpn-ip"; fi
    if [[ -n "$domain" ]]; then
        [[ "$domain" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ && "$domain" == *.* ]] \
            || die "invalid --domain"
    fi
    [[ -d "$tulip_dir" && -f "$tulip_dir/docker-compose.yml" ]] || die "Tulip checkout not found: $tulip_dir"

    install_offsite_dependencies
    need_command ssh-keygen; need_command ssh-keyscan; need_command python3; need_command rsync
    tulip_dir="$(cd -- "$tulip_dir" && pwd -P)"
    ensure_timescale_clang19 "$tulip_dir"
    mkdir -p -- "$tulip_dir/.ecsc/ssh" "$tulip_dir/.ecsc/metadata" "$tulip_dir/.ecsc/traffic"

    local private_key="$tulip_dir/.ecsc/ssh/id_ed25519"
    local public_key="$private_key.pub"
    local known_hosts="$tulip_dir/.ecsc/ssh/known_hosts"
    if [[ ! -s "$private_key" || ! -s "$public_key" ]]; then
        [[ ! -e "$private_key" && ! -e "$public_key" ]] \
            || die "incomplete SSH key pair under $tulip_dir/.ecsc/ssh"
        ssh-keygen -q -t ed25519 -N '' -C ecsc-tulip-capture -f "$private_key"
    fi
    chmod 0600 "$private_key"; chmod 0644 "$public_key"
    [[ -e "$known_hosts" ]] || : >"$known_hosts"
    chmod 0644 "$known_hosts"

    local stored_push_key="$tulip_dir/.ecsc/ssh/vulnbox-push.pub"
    if [[ -n "$push_public_key_literal" ]]; then
        printf '%s\n' "$push_public_key_literal" | write_generated "$stored_push_key" "$force" 0644
    elif [[ -n "$push_public_key_file" ]]; then
        [[ -s "$push_public_key_file" ]] || die "push public key file is empty or missing: $push_public_key_file"
        cat "$push_public_key_file" | write_generated "$stored_push_key" "$force" 0644
    fi

    if [[ -s "$stored_push_key" ]]; then
        [[ ${EUID:-$(id -u)} -eq 0 ]] || die "durable push receiver installation requires root"
        [[ "$tulip_dir" =~ ^/[A-Za-z0-9_./-]+$ ]] \
            || die "durable push requires a Tulip path without spaces or shell metacharacters"
        local push_key_type push_key_data receiver=/usr/local/sbin/rose-pcap-receive
        read -r push_key_type push_key_data _ <"$stored_push_key"
        case "$push_key_type" in ssh-ed25519|ecdsa-sha2-*|ssh-rsa) ;; *) die "unsupported forwarding SSH public key" ;; esac
        [[ "$push_key_data" =~ ^[A-Za-z0-9+/=]+$ ]] || die "invalid forwarding SSH public key"

        cat <<EOF | write_generated "$receiver" "$force" 0755
#!/usr/bin/env bash
set -Eeuo pipefail
readonly destination="$tulip_dir/.ecsc/traffic/"
readonly expected="rsync --server -logDtpre.iLsfxCIvu --timeout=20 --remove-source-files . \$destination"
case "\${SSH_ORIGINAL_COMMAND:-}" in
    health)
        printf 'rose-receiver-ok\n'
        ;;
    "\$expected")
        exec /usr/bin/rsync --server -logDtpre.iLsfxCIvu --timeout=20 --remove-source-files . "\$destination"
        ;;
    *)
        printf 'only Rose PCAP delivery is allowed\n' >&2
        exit 126
        ;;
esac
EOF
        local receiver_ssh_dir=/root/.ssh receiver_keys=/root/.ssh/authorized_keys receiver_tmp
        mkdir -p -- "$receiver_ssh_dir"; chmod 0700 "$receiver_ssh_dir"
        receiver_tmp="$(mktemp)"
        if [[ -f "$receiver_keys" ]]; then
            grep -v '[[:space:]]rose-pcap-push$' "$receiver_keys" >"$receiver_tmp" || true
        fi
        printf 'restrict,command="%s" %s %s rose-pcap-push\n' \
            "$receiver" "$push_key_type" "$push_key_data" >>"$receiver_tmp"
        install -m 0600 "$receiver_tmp" "$receiver_keys"
        rm -f -- "$receiver_tmp"
        durable_push=1
    fi

    local vm_ip="$vulnbox_ip" services_json
    services_json="$(build_services_json "$vm_ip" "${service_specs[@]}")"
    if [[ ! -e "$tulip_dir/.ecsc/metadata/services.json" ]]; then
        printf '%s\n' "$services_json" | write_generated "$tulip_dir/.ecsc/metadata/services.json" 0 0644
    elif ((force)) && ((${#service_specs[@]})); then
        printf '%s\n' "$services_json" | write_generated "$tulip_dir/.ecsc/metadata/services.json" 1 0644
    fi

    local use_caddy=1 bind_ip="127.0.0.1" ui_url site_host site_label tls_directive caddy_target_port=443
    if [[ -n "$ui_vpn_ip" ]]; then
        use_caddy=0; bind_ip="$ui_vpn_ip"; ui_url="http://$(url_host "$ui_vpn_ip"):$ui_port"
    else
        [[ -n "$domain" || -n "$public_ip" ]] || die "pass --domain or --public-ip for public HTTPS exposure, or --ui-vpn-ip for direct binding"
        if [[ -n "$domain" ]]; then
            site_host="$domain"
            ui_url="https://$(url_host "$site_host")"
            if ((public_port != 443)); then ui_url+=":$public_port"; fi
            site_label="https://$domain"
            tls_directive=""
        else
            site_host="$public_ip"
            ui_url="http://$(url_host "$site_host")"
            if ((public_port != 80)); then ui_url+=":$public_port"; fi
            site_label=":80"
            tls_directive=""
            caddy_target_port=80
        fi
        need_command openssl
        local password_file="$tulip_dir/.ecsc/public-auth-password"
        local hash_file="$tulip_dir/.ecsc/public-auth-hash"
        if [[ -z "$auth_password" && -s "$password_file" ]]; then auth_password="$(<"$password_file")"; fi
        [[ -n "$auth_password" ]] || auth_password="$(openssl rand -hex 16)"
        printf '%s\n' "$auth_password" | write_generated "$password_file" "$force" 0600
        local auth_hash
        if [[ -s "$hash_file" && "$force" != 1 ]]; then
            auth_hash="$(<"$hash_file")"
        else
            auth_hash="$(docker run --rm "$CADDY_IMAGE" caddy hash-password --plaintext "$auth_password")"
        fi
        printf '%s\n' "$auth_hash" | write_generated "$hash_file" "$force" 0600
        cat <<EOF | write_generated "$tulip_dir/Caddyfile.ecsc" "$force" 0644
$site_label {
    $tls_directive
    header {
        Strict-Transport-Security "max-age=31536000"
        X-Content-Type-Options "nosniff"
        Referrer-Policy "no-referrer"
        -Server
    }
    basic_auth {
        $auth_user $auth_hash
    }
    encode zstd gzip
    reverse_proxy frontend:3000
}
EOF
    fi

    cat <<EOF | write_generated "$tulip_dir/.env.ecsc" "$force" 0600
TIMESCALE=postgresql://tulip@timescale:5432/tulip
TRAFFIC_DIR_HOST=$tulip_dir/.ecsc/traffic
TRAFFIC_DIR_DOCKER=/traffic
TULIP_BIND_IP=$bind_ip
TULIP_UI_PORT=$ui_port
FLAG_REGEX='ECSC\{[A-Za-z0-9_-]{32}\}'
TICK_START=$tick_start
TICK_LENGTH=$FAUST_TICK_LENGTH_MS
FLAG_LIFETIME=$FAUST_FLAG_LIFETIME_TICKS
VM_IP=$vm_ip
SERVICES_JSON=$services_json
TEAM_ID=$team_id
FLAGID_SCRAPE=0
FLAGID_ENDPOINT=
VISUALIZER_URL=
FLAGID_SCAN=0
FLAG_VALIDATOR_TYPE=
FLAG_VALIDATOR_TEAM=
PCAP_OVER_IP=$([[ "$durable_push" == 1 ]] && printf '' || printf 'pcap-broker:4242')
DUMP_PCAPS=
DUMP_PCAPS_INTERVAL=0
DUMP_PCAPS_FILENAME=
BPF=tcp and not port 22 and not port 4444
EOF

    cat <<EOF | write_generated "$tulip_dir/.ecsc/service-sync.sh" "$force" 0755
#!/bin/sh
set -eu
while true; do
    temporary="\$(mktemp)"
    if ssh -i /root/.ssh/id_ed25519 -o BatchMode=yes -o StrictHostKeyChecking=yes \
        -o ConnectTimeout=10 root@$vulnbox_ip services >"\$temporary"; then
        cp "\$temporary" /config/.services.json
        mv /config/.services.json /config/services.json
    fi
    rm -f -- "\$temporary"
    sleep 60
done
EOF

    {
        cat <<EOF
services:
EOF
        if ((durable_push == 0)); then
            cat <<EOF
  pcap-broker:
    build:
      context: https://github.com/fox-it/pcap-broker.git#$PCAP_BROKER_REV
    image: ecsc-pcap-broker:latest
    restart: unless-stopped
    network_mode: host
    volumes:
      - ./.ecsc/ssh/id_ed25519:/root/.ssh/id_ed25519:ro
      - ./.ecsc/ssh/known_hosts:/root/.ssh/known_hosts:ro
    environment:
      LISTEN_ADDRESS: 0.0.0.0:4242
      PCAP_COMMAND: ssh -i /root/.ssh/id_ed25519 -o BatchMode=yes -o StrictHostKeyChecking=yes -o ConnectTimeout=10 -o ServerAliveInterval=30 -o ServerAliveCountMax=3 -o TCPKeepAlive=yes root@$vulnbox_ip capture

EOF
        fi
        cat <<EOF
  service-sync:
    build:
      context: https://github.com/fox-it/pcap-broker.git#$PCAP_BROKER_REV
    image: ecsc-pcap-broker:latest
    restart: unless-stopped
    entrypoint: /bin/sh
    command: /sync/service-sync.sh
EOF
        if ((durable_push == 0)); then
            cat <<EOF
    depends_on:
      - pcap-broker
EOF
        fi
        cat <<EOF
    network_mode: host
    volumes:
      - ./.ecsc/ssh/id_ed25519:/root/.ssh/id_ed25519:ro
      - ./.ecsc/ssh/known_hosts:/root/.ssh/known_hosts:ro
      - ./.ecsc/service-sync.sh:/sync/service-sync.sh:ro
      - ./.ecsc/metadata:/config

  api:
    volumes:
      - ./.ecsc/metadata:/config:ro
    environment:
      SERVICES_FILE: /config/services.json

  assembler:
    depends_on:
      - timescale
EOF
        if ((durable_push == 0)); then
            cat <<EOF
      - pcap-broker
EOF
        fi
        cat <<EOF
    environment:
      PCAP_OVER_IP: $([[ "$durable_push" == 1 ]] && printf '""' || printf 'host.docker.internal:4242')
    extra_hosts:
      - "host.docker.internal:host-gateway"
EOF
        if ((use_caddy)); then
            cat <<EOF

  caddy:
    image: $CADDY_IMAGE
    restart: unless-stopped
    ports:
      - "$public_port:$caddy_target_port"
    networks:
      - internal
    depends_on:
      - frontend
    volumes:
      - ./Caddyfile.ecsc:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config

volumes:
  caddy-data:
  caddy-config:
EOF
        fi
    } | write_generated "$tulip_dir/docker-compose.ecsc.yml" "$force" 0644

    log "offsite configuration ready"
    log "install this restricted key on the vulnbox: $public_key"
    if ((durable_push)); then
        log "ingest mode: durable vulnbox push with local retry queue"
    else
        log "ingest mode: legacy live stream; configure --push-public-key-file for disconnect-safe forwarding"
    fi
    log "UI: $ui_url"
    if ((use_caddy)); then log "UI user: $auth_user; password: $auth_password"; fi

    if ((start)); then
        local scan_tmp
        scan_tmp="$(mktemp)"
        if ! ssh-keyscan -T 5 "$vulnbox_ip" >"$scan_tmp" 2>/dev/null || [[ ! -s "$scan_tmp" ]]; then
            rm -f -- "$scan_tmp"
            die "cannot read the SSH host key from $vulnbox_ip; check the game VPN and vulnbox setup"
        fi
        if [[ -s "$known_hosts" ]]; then
            rm -f -- "$scan_tmp"
        else
            chmod 0644 "$scan_tmp"
            mv -f -- "$scan_tmp" "$known_hosts"
        fi

        ssh -i "$private_key" -o BatchMode=yes -o StrictHostKeyChecking=yes -o ConnectTimeout=10 \
            root@"$vulnbox_ip" services | python3 -m json.tool >/dev/null \
            || die "restricted SSH service check failed; run vulnbox mode first"
        (
            cd -- "$tulip_dir"
            docker compose --env-file .env.ecsc -f docker-compose.yml -f docker-compose.ecsc.yml config >/dev/null
            docker compose --env-file .env.ecsc -f docker-compose.yml -f docker-compose.ecsc.yml up -d --build
            if ((durable_push)); then
                docker rm -f "$(basename "$tulip_dir")-pcap-broker-1" >/dev/null 2>&1 || true
            fi
        )
        log "Rose and traffic ingestion started"
    fi
}

